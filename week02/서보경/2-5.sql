
SELECT
    YEAR(os.SALES_DATE) AS YEAR,
    MONTH(os.SALES_DATE) AS MONTH,
    ui.GENDER,
    COUNT(DISTINCT ui.USER_ID) AS USERS
FROM ONLINE_SALE os
LEFT JOIN USER_INFO ui
ON os.USER_ID = ui.USER_ID
WHERE ui.GENDER IS NOT NULL
GROUP BY
    YEAR(os.SALES_DATE),
    MONTH(os.SALES_DATE),
    ui.GENDER
ORDER BY
    YEAR ASC, MONTH ASC, ui.GENDER ASC;